#!/usr/bin/env bash
# 20-postfix — the MTA. Idempotent. Backlog: E03-015..E03-024.
#
# NON-NEGOTIABLE: this configuration is not an open relay, and 90-verify.sh
# proves it before the node is allowed to carry traffic.
set -euo pipefail
cd "$(dirname "$0")"
# shellcheck source=/dev/null
source node.env
export DEBIAN_FRONTEND=noninteractive

debconf-set-selections <<< "postfix postfix/main_mailer_type string 'Internet Site'"
debconf-set-selections <<< "postfix postfix/mailname string ${NODE_HOSTNAME}"
apt-get install -y -qq postfix postfix-pcre

# ── Per-ESP concurrency and rate delay. Google, Microsoft and Yahoo tolerate
#    very different shapes; one global setting is wrong for all three.
cat > /etc/postfix/transport <<'EOF'
# receiving-domain            transport:nexthop
gmail.com                     smtp-google:
googlemail.com                smtp-google:
outlook.com                   smtp-microsoft:
hotmail.com                   smtp-microsoft:
live.com                      smtp-microsoft:
yahoo.com                     smtp-yahoo:
EOF
postmap /etc/postfix/transport

# ── Sender-dependent transports: per-domain queue behaviour, and the hook for
#    binding a specific source IP per sending domain on a multi-IP node.
touch /etc/postfix/sender_transport
postmap /etc/postfix/sender_transport

# ── The relay allowlist. Loopback plus the workers' private IP. Nothing else.
cat > /etc/postfix/mynetworks <<EOF
127.0.0.0/8
${WORKERS_PRIVATE_IP}/32
EOF

main=/etc/postfix/main.cf
cat > "$main" <<EOF
# Generated by infra/blast-node/20-postfix.sh — edit the template, not the host.
compatibility_level = 3.6
myhostname = ${NODE_HOSTNAME}
mydomain = ${NODE_HOSTNAME#*.}
myorigin = \$myhostname
mydestination =
inet_interfaces = all
inet_protocols = ipv4

# ── Relay control. reject_unauth_destination is what makes this not an open relay.
mynetworks = /etc/postfix/mynetworks
smtpd_relay_restrictions =
    permit_mynetworks
    reject_unauth_destination
smtpd_recipient_restrictions =
    permit_mynetworks
    reject_unauth_destination
    reject_non_fqdn_recipient
    reject_unknown_recipient_domain
smtpd_sender_restrictions =
    permit_mynetworks
    reject_non_fqdn_sender
    reject_unknown_sender_domain
smtpd_helo_required = yes

# ── Outbound source binding. On a multi-IP node the per-transport override in
#    master.cf wins; this is the default.
smtp_bind_address = ${NODE_IP}

# ── Retries belong to our scheduler, not to Postfix's queue.
soft_bounce = no
maximal_queue_lifetime = 2h
bounce_queue_lifetime = 2h
minimal_backoff_time = 300s
maximal_backoff_time = 1800s

# ── VERP: exact bounce attribution per message.
default_verp_delimiters = +=
verp_delimiter_filter = -+=

# ── Transports
transport_maps = hash:/etc/postfix/transport
sender_dependent_default_transport_maps = hash:/etc/postfix/sender_transport

# ── TLS. Opportunistic outbound, real certificate inbound (installed by 70-tls.sh).
smtp_tls_security_level = may
smtp_tls_loglevel = 1
smtp_tls_note_starttls_offer = yes
smtpd_tls_security_level = may
smtpd_tls_loglevel = 1

# ── DKIM / DMARC milters (configured by 30-opendkim.sh and 50-dmarc.sh)
milter_default_action = accept
milter_protocol = 6
smtpd_milters = inet:127.0.0.1:8891, inet:127.0.0.1:8893
non_smtpd_milters = inet:127.0.0.1:8891

# ── Conservative global ceilings. Per-mailbox pacing is enforced upstream by
#    @ems/router; this is only a safety net (E03-081).
default_destination_concurrency_limit = 5
default_destination_rate_delay = 1s
smtp_destination_concurrency_limit = 5

message_size_limit = 15728640
biff = no
append_dot_mydomain = no
readme_directory = no
EOF

master=/etc/postfix/master.cf
if ! grep -q "smtp-google" "$master"; then
cat >> "$master" <<EOF

# ── Per-ESP transports (added by 20-postfix.sh)
smtp-google   unix - - n - - smtp
    -o smtp_destination_concurrency_limit=3
    -o smtp_destination_rate_delay=2s
    -o syslog_name=postfix-google
smtp-microsoft unix - - n - - smtp
    -o smtp_destination_concurrency_limit=2
    -o smtp_destination_rate_delay=3s
    -o syslog_name=postfix-microsoft
smtp-yahoo    unix - - n - - smtp
    -o smtp_destination_concurrency_limit=2
    -o smtp_destination_rate_delay=4s
    -o syslog_name=postfix-yahoo
EOF
fi

postfix check
systemctl enable --now postfix
systemctl reload postfix
echo "  20-postfix: done"
